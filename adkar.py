def combien():
    """Nombre de noms disponibles."""
    return len(ENTREES)


def entree(rang):
    """Nom numero rang, en bouclant sur la liste."""
    if not ENTREES:
        return None
    return ENTREES[rang % len(ENTREES)]


def largeur(motif):
    """Largeur en pixels d'un motif arabe."""
    return len(motif[0]) if motif else 0
