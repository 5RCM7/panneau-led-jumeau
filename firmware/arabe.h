struct MotArabe { const char *nom; const char **motif; int16_t largeur; };

static const MotArabe ARABE_MOTS[] = {
    {"FAJR", ARABE_FAJR, 27},
    {"DOHR", ARABE_DOHR, 29},
    {"ASR", ARABE_ASR, 32},
    {"MAGHREB", ARABE_MAGHREB, 37},
    {"ICHA", ARABE_ICHA, 34},
    {"JOUMOUA", ARABE_JOUMOUA, 35},
};
static const int8_t ARABE_COUNT = 6;

// Silhouette d'un nom de priere, ou nullptr si inconnu.
static const MotArabe *arabePour(const char *nom) {
  for (int8_t i = 0; i < ARABE_COUNT; i++)
    if (strcmp(ARABE_MOTS[i].nom, nom) == 0) return &ARABE_MOTS[i];
  return nullptr;
}

