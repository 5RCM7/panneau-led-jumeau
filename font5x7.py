GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
ADVANCE = 6  # 5 colonnes + 1 colonne de separation

ARROW = "\x01"
PLANE = "\x02"
DEGRE = "\x03"

_FALLBACK = GLYPHS["?"]


def glyph(char):
    """Renvoie le motif d'un caractere, en majuscule, avec repli sur '?'."""
    return GLYPHS.get(char.upper(), _FALLBACK)


def affichable(texte):
    """Reduit un texte a ce que la police sait dessiner.

    Les APIs renvoient des noms accentues - Sao Paulo, Nimes, Malaga - que la
    police ignore et remplacerait par des '?'. On enleve les accents plutot
    que de perdre les lettres, et on jette le reste : sur un panneau LED, une
    lettre approchee vaut mieux qu'un point d'interrogation.
    """
    if not texte:
        return texte
    decompose = unicodedata.normalize("NFKD", texte)
    sans_accent = "".join(c for c in decompose if not unicodedata.combining(c))
    return "".join(c for c in sans_accent if c.upper() in GLYPHS)


def text_width(text):
    """Largeur en pixels d'une chaine rendue avec cette police."""
    if not text:
        return 0
    return len(text) * ADVANCE - 1
